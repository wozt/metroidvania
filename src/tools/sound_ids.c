/* Writes or checks src/runtime/mzm_sound_ids.h, the MZM_ identifiers of the
 * Sound enum of the pinned decompilation (include/constants/audio.h, whose
 * members are consecutive from 0). Only identifiers, no sound data. */
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef FUSION_SOURCE_DIR
#error "FUSION_SOURCE_DIR must identify the repository source directory"
#endif

static const char header_path[] = FUSION_SOURCE_DIR "/src/runtime/mzm_sound_ids.h";
static const char source_path[] = FUSION_SOURCE_DIR "/third_party/mzm/include/constants/audio.h";

static char *read_all(const char *path, size_t *size) {
    FILE *file = fopen(path, "rb");
    if (!file) return NULL;
    char *text = NULL;
    size_t used = 0, capacity = 0, read;
    char chunk[65536];
    while ((read = fread(chunk, 1, sizeof chunk, file)) > 0) {
        if (used + read + 1 > capacity) {
            capacity = (used + read + 1) * 2;
            char *grown = realloc(text, capacity);
            if (!grown) {
                free(text);
                fclose(file);
                return NULL;
            }
            text = grown;
        }
        memcpy(text + used, chunk, read);
        used += read;
    }
    fclose(file);
    if (!text) text = calloc(1, 1);
    else text[used] = '\0';
    if (size) *size = used;
    return text;
}

/* The header text, or NULL when the enum is missing. */
static char *render(const char *source) {
    const char *start = strstr(source, "MAKE_ENUM(u16, Sound)");
    const char *open = start ? strchr(start, '{') : NULL;
    const char *close = open ? strstr(open, "};") : NULL;
    if (!close) return NULL;
    size_t capacity = 64 * 1024, used = 0;
    char *out = malloc(capacity);
    if (!out) return NULL;
    used += (size_t)snprintf(out, capacity,
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* Generated by fusion_sound_ids from the Sound enum of the pinned\n"
        " * decompilation (include/constants/audio.h); do not edit. */\n"
        "#ifndef MZM_SOUND_IDS_H\n#define MZM_SOUND_IDS_H\n\nenum {\n");
    unsigned value = 0;
    const char *cursor = open + 1;
    while (cursor < close) {
        if (cursor[0] == '/' && cursor[1] == '/') {
            while (cursor < close && *cursor != '\n') ++cursor;
            continue;
        }
        if (cursor[0] == '/' && cursor[1] == '*') {
            const char *end = strstr(cursor + 2, "*/");
            cursor = end ? end + 2 : close;
            continue;
        }
        if ((*cursor >= 'A' && *cursor <= 'Z') || (*cursor >= 'a' && *cursor <= 'z') ||
            *cursor == '_') {
            const char *name = cursor;
            while (cursor < close && ((*cursor >= 'A' && *cursor <= 'Z') ||
                                      (*cursor >= 'a' && *cursor <= 'z') ||
                                      (*cursor >= '0' && *cursor <= '9') || *cursor == '_'))
                ++cursor;
            if (used + 128 + (size_t)(cursor - name) > capacity) {
                capacity *= 2;
                char *grown = realloc(out, capacity);
                if (!grown) {
                    free(out);
                    return NULL;
                }
                out = grown;
            }
            used += (size_t)snprintf(out + used, capacity - used, "    MZM_%.*s = 0x%X,\n",
                                     (int)(cursor - name), name, value++);
            continue;
        }
        ++cursor;
    }
    snprintf(out + used, capacity - used, "};\n\n#endif /* MZM_SOUND_IDS_H */\n");
    return out;
}

int main(int argc, char **argv) {
    bool check = argc == 2 && !strcmp(argv[1], "--check");
    bool write = argc == 2 && !strcmp(argv[1], "--write");
    if (!check && !write) {
        fprintf(stderr, "usage: %s --check | --write\n", argv[0]);
        return 2;
    }
    char *source = read_all(source_path, NULL);
    char *text = source ? render(source) : NULL;
    free(source);
    if (!text) {
        fprintf(stderr, "no Sound enum in %s\n", source_path);
        return 1;
    }
    int status = 0;
    if (check) {
        char *current = read_all(header_path, NULL);
        if (!current || strcmp(current, text)) {
            printf("src/runtime/mzm_sound_ids.h is stale: build/fusion_sound_ids --write\n");
            status = 1;
        } else {
            printf("src/runtime/mzm_sound_ids.h is fresh\n");
        }
        free(current);
    } else {
        FILE *file = fopen(header_path, "wb");
        if (!file || fputs(text, file) < 0 || fclose(file) != 0) {
            fprintf(stderr, "cannot write %s\n", header_path);
            status = 1;
        } else {
            printf("Wrote src/runtime/mzm_sound_ids.h\n");
        }
    }
    free(text);
    return status;
}
