"""The ``Sound`` enum of the pinned Zero Mission decompilation as a C header.

Writes ``src/runtime/mzm_sound_ids.h`` (``MZM_SOUND_*`` and ``MZM_MUSIC_*``
from ``include/constants/audio.h``) for the gameplay modules' sound requests.
Only identifiers are generated, no sound data. ``--check`` fails when the
header is stale.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import mzm_c_tables  # noqa: E402

DECOMP = ROOT / "third_party/mzm"
HEADER = ROOT / "src/runtime/mzm_sound_ids.h"


def sound_names(decomp: Path = DECOMP) -> list[tuple[str, int]]:
    """The members of ``MAKE_ENUM(u16, Sound)`` with their values."""
    text = (decomp / "include/constants/audio.h").read_text(encoding="utf-8")
    values = mzm_c_tables.enum_values(decomp)
    for name, body in mzm_c_tables.ENUM_RE.findall(text):
        if name != "Sound":
            continue
        body = mzm_c_tables._strip_comments(body)
        members = [item.split("=")[0].strip() for item in body.split(",")]
        return [(member, values[member]) for member in members if member]
    raise ValueError("no Sound enum in include/constants/audio.h")


def render(decomp: Path = DECOMP) -> str:
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
             "/* Generated by scripts/mzm_sound_ids.py from the Sound enum of the pinned",
             " * decompilation (include/constants/audio.h); do not edit. */",
             "#ifndef MZM_SOUND_IDS_H", "#define MZM_SOUND_IDS_H", "", "enum {"]
    lines += [f"    MZM_{name} = 0x{value:X}," for name, value in sound_names(decomp)]
    lines += ["};", "", "#endif /* MZM_SOUND_IDS_H */", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the header is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != text:
            print(f"{HEADER.relative_to(ROOT)} is stale: python3 -m scripts.mzm_sound_ids")
            return 1
        print(f"{HEADER.relative_to(ROOT)} is fresh")
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"Wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
